/**
 * Regenerates lib/brand-icons.generated.ts from the simple-icons dataset.
 *
 * simple-icons is a devDependency only: the brand paths are inlined at build
 * time so the icon set never ships in the client bundle.
 *
 * Usage: node scripts/generate-brand-icons.mjs
 */
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import path from "node:path"

import * as simpleIcons from "simple-icons"

const SLUGS = [
  "laravel",
  "php",
  "mysql",
  "redis",
  "flutter",
  "dart",
  "android",
  "ios",
  "firebase",
  "googleads",
  "meta",
  "googleanalytics",
  "googlesearchconsole",
  "semrush",
  "dotnet",
  "html5",
  "bootstrap",
  "javascript",
  "jquery",
  "linux",
  "xml",
  "json",
  "css",
  // WARS LAB / GovTech stack
  "python",
  "fastapi",
  "postgresql",
  "rabbitmq",
  "react",
  "angular",
  "typescript",
  "openjdk",
  "springboot",
  "docker",
  "nginx",
  "openssl",
  "jsonwebtokens",
  "auth0",
  "keycloak",
  "letsencrypt",
  "ieee",
  "openapiinitiative",
  "webauthn",
  // Rota Legal / LPR stack
  "go",
  "mongodb",
  "elasticsearch",
  "apachekafka",
  "sqlite",
  "kubernetes",
]

const entries = SLUGS.map((slug) => {
  const key = `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`
  const icon = simpleIcons[key]

  if (!icon) throw new Error(`simple-icons is missing "${key}"`)

  return { slug, title: icon.title, hex: icon.hex, path: icon.path }
})

const body = entries
  .map(
    ({ slug, title, hex, path: d }) =>
      `  "${slug}": {\n    title: ${JSON.stringify(title)},\n    hex: "#${hex}",\n    path: ${JSON.stringify(d)},\n  },`
  )
  .join("\n")

const file = `// Generated by scripts/generate-brand-icons.mjs — do not edit by hand.
// Brand marks are trademarks of their respective owners.

export type BrandIcon = {
  title: string
  hex: string
  path: string
}

export const BRAND_ICONS: Record<string, BrandIcon> = {
${body}
}
`

const outPath = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "lib",
  "brand-icons.generated.ts"
)

writeFileSync(outPath, file, "utf8")
console.log(`Wrote ${entries.length} brand icons to ${outPath}`)
